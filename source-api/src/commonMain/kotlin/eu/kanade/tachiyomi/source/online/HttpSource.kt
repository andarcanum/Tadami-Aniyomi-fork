/**
 * A simple implementation for sources from a website.
 */
@Suppress("unused")
abstract class HttpSource : CatalogueSource {

    /**
     * Network service.
     */
    protected val network: NetworkHelper by injectLazy()

    /**
     * Base url of the website without the trailing slash, like: http://mysite.com
     */
    abstract val baseUrl: String

    /**
     * Returns the base (home) URL of the website as a string.
     *
     * Used in the browse screen to determine the URL opened when tapping
     * "Open in WebView".
     *
     * @since extensions-lib 1.6
     * @return the website's home page URL. Defaults to [baseUrl].
     */
    open fun getHomeUrl(): String = baseUrl

    /**
     * Version id used to generate the source id. If the site completely changes and urls are
     * incompatible, you may increase this value and it'll be considered as a new source.
     */
    open val versionId = 1

    /**
     * ID of the source. By default it uses a generated id using the first 16 characters (64 bits)
     * of the MD5 of the string `"${name.lowercase()}/$lang/$versionId"`.
     *
     * The ID is generated by the [generateId] function, which can be reused if needed
     * to generate outdated IDs for cases where the source name or language needs to
     * be changed but migrations can be avoided.
     *
     * Note: the generated ID sets the sign bit to `0`.
     */
    override val id by lazy { generateId(name, lang, versionId) }

    /**
     * Headers used for requests.
     */
    val headers: Headers by lazy { headersBuilder().build() }

    /**
     * Default network client for doing requests.
     */
    open val client: OkHttpClient
        get() = network.client

    /**
     * Generates a unique ID for the source based on the provided [name], [lang] and
     * [versionId]. It will use the first 16 characters (64 bits) of the MD5 of the string
     * `"${name.lowercase()}/$lang/$versionId"`.
     *
     * Note: the generated ID sets the sign bit to `0`.
     *
     * Can be used to generate outdated IDs, such as when the source name or language
     * needs to be changed but migrations can be avoided.
     *
     * @since extensions-lib 1.5
     * @param name [String] the name of the source
     * @param lang [String] the language of the source
     * @param versionId [Int] the version ID of the source
     * @return a unique ID for the source
     */
    @Suppress("MemberVisibilityCanBePrivate")
    protected fun generateId(name: String, lang: String, versionId: Int): Long {
        val key = "${name.lowercase()}/$lang/$versionId"
        val bytes = MessageDigest.getInstance("MD5").digest(key.toByteArray())
        return (0..7).map { bytes[it].toLong() and 0xff shl 8 * (7 - it) }.reduce(Long::or) and Long.MAX_VALUE
    }

    /**
     * Headers builder for requests. Implementations can override this method for custom headers.
     */
    protected open fun headersBuilder() = Headers.Builder().apply {
        add("User-Agent", network.defaultUserAgentProvider())
    }

    /**
     * Visible name of the source.
     */
    override fun toString() = "$name (${lang.uppercase()})"

    /**
     * Returns an observable containing a page with a list of manga. Normally it's not needed to
     * override this method.
     *
     * @param page the page number to retrieve.
     */
    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getPopularManga"))
    override fun fetchPopularManga(page: Int): Observable<MangasPage> {
        return client.newCall(popularMangaRequest(page))
            .asObservableSuccess()
            .map { response ->
                popularMangaParse(response)
            }
    }

    /**
     * Returns the request for the popular manga given the page.
     *
     * @param page the page number to retrieve.
     */
    protected open fun popularMangaRequest(page: Int): Request = throw UnsupportedOperationException()

    /**
     * Parses the response from the site and returns a [MangasPage] object.
     *
     * @param response the response from the site.
     */
    protected open fun popularMangaParse(response: Response): MangasPage = throw UnsupportedOperationException()

    /**
     * Returns an observable containing a page with a list of manga. Normally it's not needed to
     * override this method.
     *
     * @param page the page number to retrieve.
     * @param query the search query.
     * @param filters the list of filters to apply.
     */
    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getSearchManga"))
    override fun fetchSearchManga(
        page: Int,
        query: String,
        filters: FilterList,
    ): Observable<MangasPage> {
        return Observable.defer {
            try {
                client.newCall(searchMangaRequest(page, query, filters)).asObservableSuccess()
            } catch (e: NoClassDefFoundError) {
                // RxJava doesn't handle Errors, which tends to happen during global searches
                // if an old extension using non-existent classes is still around
                throw RuntimeException(e)
            }
        }
            .map { response ->
                searchMangaParse(response)
            }
    }

    /**
     * Returns the request for the search manga given the page.
     *
     * @param page the page number to retrieve.
     * @param query the search query.
     * @param filters the list of filters to apply.
     */
    protected open fun searchMangaRequest(
        page: Int,
        query: String,
        filters: FilterList,
    ): Request = throw UnsupportedOperationException()

    /**
     * Parses the response from the site and returns a [MangasPage] object.
     *
     * @param response the response from the site.
     */
    protected open fun searchMangaParse(response: Response): MangasPage = throw UnsupportedOperationException()

    /**
     * Returns an observable containing a page with a list of latest manga updates.
     *
     * @param page the page number to retrieve.
     */
    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getLatestUpdates"))
    override fun fetchLatestUpdates(page: Int): Observable<MangasPage> {
        return client.newCall(latestUpdatesRequest(page))
            .asObservableSuccess()
            .map { response ->
                latestUpdatesParse(response)
            }
    }

    /**
     * Returns the request for latest manga given the page.
     *
     * @param page the page number to retrieve.
     */
    protected open fun latestUpdatesRequest(page: Int): Request = throw UnsupportedOperationException()

    /**
     * Parses the response from the site and returns a [MangasPage] object.
     *
     * @param response the response from the site.
     */
    protected open fun latestUpdatesParse(response: Response): MangasPage = throw UnsupportedOperationException()

    /**
     * Get the updated details for a manga.
     * Normally it's not needed to override this method.
     *
     * @param manga the manga to be updated.
     * @return the updated manga.
     */
    @Suppress("DEPRECATION")
    override suspend fun getMangaDetails(manga: SManga): SManga {
        return fetchMangaDetails(manga).awaitSingle()
    }

    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getMangaDetails"))
    override fun fetchMangaDetails(manga: SManga): Observable<SManga> {
        return client.newCall(mangaDetailsRequest(manga))
            .asObservableSuccess()
            .map { response ->
                mangaDetailsParse(response).apply { initialized = true }
            }
    }

    /**
     * Returns the request for the details of a manga. Override only if it's needed to change the
     * url, send different headers or request method like POST.
     *
     * @param manga the manga to be updated.
     */
    open fun mangaDetailsRequest(manga: SManga): Request {
        return GET(baseUrl + manga.url, headers)
    }

    /**
     * Parses the response from the site and returns the details of a manga.
     *
     * @param response the response from the site.
     */
    protected open fun mangaDetailsParse(response: Response): SManga = throw UnsupportedOperationException()

    /**
     * Get all the available chapters for a manga.
     * Normally it's not needed to override this method.
     *
     * @param manga the manga to update.
     * @return the chapters for the manga.
     */
    @Suppress("DEPRECATION")
    override suspend fun getChapterList(manga: SManga): List<SChapter> {
        val cacheKey = "${id}_${manga.url}"
        val cached = chapterListCache[cacheKey]
        if (cached != null) {
            return cached
        }
        val chapters = fetchChapterList(manga).awaitSingle()
        chapterListCache[cacheKey] = chapters

        mangaToChapters[cacheKey] = chapters
        chapters.forEach { chapter ->
            chapterToMangaUrl["${id}_${chapter.url}"] = cacheKey
        }
        return chapters
    }

    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getChapterList"))
    override fun fetchChapterList(manga: SManga): Observable<List<SChapter>> {
        val cacheKey = "${id}_${manga.url}"
        val cached = chapterListCache[cacheKey]
        if (cached != null) {
            return Observable.just(cached)
        }
        return client.newCall(chapterListRequest(manga))
            .asObservableSuccess()
            .map { response ->
                val chapters = chapterListParse(response)
                chapterListCache[cacheKey] = chapters

                mangaToChapters[cacheKey] = chapters
                chapters.forEach { chapter ->
                    chapterToMangaUrl["${id}_${chapter.url}"] = cacheKey
                }
                chapters
            }
    }

    /**
     * Returns the request for updating the chapter list. Override only if it's needed to override
     * the url, send different headers or request method like POST.
     *
     * @param manga the manga to look for chapters.
     */
    protected open fun chapterListRequest(manga: SManga): Request {
        return GET(baseUrl + manga.url, headers)
    }

    /**
     * Parses the response from the site and returns a list of chapters.
     *
     * @param response the response from the site.
     */
    protected open fun chapterListParse(response: Response): List<SChapter> = throw UnsupportedOperationException()

    /**
     * Parses the response from the site and returns a SChapter Object.
     *
     * @param response the response from the site.
     */
    protected open fun chapterPageParse(response: Response): SChapter = throw UnsupportedOperationException()

    /**
     * Get the list of pages a chapter has. Pages should be returned
     * in the expected order; the index is ignored.
     *
     * @param chapter the chapter.
     * @return the pages for the chapter.
     */
    @Suppress("DEPRECATION")
    override suspend fun getPageList(chapter: SChapter): List<Page> {
        val cacheKey = "${id}_${chapter.url}"
        val cached = pageListCache[cacheKey]
        if (cached != null) {
            triggerNextChapterPrefetch(chapter)
            return cached
        }
        val pages = fetchPageList(chapter).awaitSingle()
        pageListCache[cacheKey] = pages

        pages.forEachIndexed { index, page ->
            val nextPage = pages.getOrNull(index + 1)
            if (nextPage != null) {
                pageToNextPage["${id}_${page.url}"] = nextPage
            }
        }

        triggerNextChapterPrefetch(chapter)
        return pages
    }

    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getPageList"))
    override fun fetchPageList(chapter: SChapter): Observable<List<Page>> {
        val cacheKey = "${id}_${chapter.url}"
        val cached = pageListCache[cacheKey]
        if (cached != null) {
            triggerNextChapterPrefetch(chapter)
            return Observable.just(cached)
        }
        return client.newCall(pageListRequest(chapter))
            .asObservableSuccess()
            .map { response ->
                val pages = pageListParse(response)
                pageListCache[cacheKey] = pages

                pages.forEachIndexed { index, page ->
                    val nextPage = pages.getOrNull(index + 1)
                    if (nextPage != null) {
                        pageToNextPage["${id}_${page.url}"] = nextPage
                    }
                }

                triggerNextChapterPrefetch(chapter)
                pages
            }
    }

    /**
     * Returns the request for getting the page list. Override only if it's needed to override the
     * url, send different headers or request method like POST.
     *
     * @param chapter the chapter whose page list has to be fetched.
     */
    protected open fun pageListRequest(chapter: SChapter): Request {
        return GET(baseUrl + chapter.url, headers)
    }

    /**
     * Parses the response from the site and returns a list of pages.
     *
     * @param response the response from the site.
     */
    protected open fun pageListParse(response: Response): List<Page> = throw UnsupportedOperationException()

    /**
     * Returns an observable with the page containing the source url of the image. If there's any
     * error, it will return null instead of throwing an exception.
     *
     * @since extensions-lib 1.5
     * @param page the page whose source image has to be fetched.
     */
    @Suppress("DEPRECATION")
    open suspend fun getImageUrl(page: Page): String {
        val cachedUrl = page.imageUrl
        if (cachedUrl != null) {
            triggerNextPagePrefetch(page)
            return cachedUrl
        }
        val url = fetchImageUrl(page).awaitSingle()
        page.imageUrl = url
        triggerNextPagePrefetch(page)
        return url
    }

    @Deprecated("Use the non-RxJava API instead", replaceWith = ReplaceWith("getImageUrl"))
    open fun fetchImageUrl(page: Page): Observable<String> {
        val cachedUrl = page.imageUrl
        if (cachedUrl != null) {
            triggerNextPagePrefetch(page)
            return Observable.just(cachedUrl)
        }
        return client.newCall(imageUrlRequest(page))
            .asObservableSuccess()
            .map { response ->
                val url = imageUrlParse(response)
                page.imageUrl = url
                triggerNextPagePrefetch(page)
                url
            }
    }

    /**
     * Returns the request for getting the url to the source image. Override only if it's needed to
     * override the url, send different headers or request method like POST.
     *
     * @param page the chapter whose page list has to be fetched
     */
    protected open fun imageUrlRequest(page: Page): Request {
        return GET(page.url, headers)
    }

    /**
     * Parses the response from the site and returns the absolute url to the source image.
     *
     * @param response the response from the site.
     */
    protected open fun imageUrlParse(response: Response): String = throw UnsupportedOperationException()

    /**
     * Returns the response of the source image.
     * Typically does not need to be overridden.
     *
     * @since extensions-lib 1.5
     * @param page the page whose source image has to be downloaded.
     */
    open suspend fun getImage(page: Page): Response {
        triggerNextPagePrefetch(page)
        return client.newCachelessCallWithProgress(
            imageRequest(page),
            page,
            // A single manga image is small; the large-media default (30h) let one stalled CDN
            // connection block a page-loader worker indefinitely.
            callTimeoutMinutes = IMAGE_CALL_TIMEOUT_MINUTES,
        )
            .awaitSuccess()
    }

    /**
     * Returns the request for getting the source image. Override only if it's needed to override
     * the url, send different headers or request method like POST.
     *
     * @param page the chapter whose page list has to be fetched
     */
    protected open fun imageRequest(page: Page): Request {
        return GET(page.imageUrl!!, headers)
    }

    private fun triggerNextChapterPrefetch(chapter: SChapter) {
        val chapterKey = "${id}_${chapter.url}"
        val mangaKey = chapterToMangaUrl[chapterKey] ?: return
        val chapters = mangaToChapters[mangaKey] ?: return
        val currentIndex = chapters.indexOfFirst { it.url == chapter.url }
        if (currentIndex < 0) return

        val adjacentChapters = listOfNotNull(
            chapters.getOrNull(currentIndex - 1),
            chapters.getOrNull(currentIndex + 1),
        )

        adjacentChapters.forEach { nextCh ->
            val nextChKey = "${id}_${nextCh.url}"
            if (!pageListCache.containsKey(nextChKey)) {
                prefetchPageList(nextCh)
            }
        }
    }

    @Suppress("DEPRECATION")
    private fun prefetchPageList(chapter: SChapter) {
        val nextChKey = "${id}_${chapter.url}"
        if (inFlightPrefetches.putIfAbsent(nextChKey, true) == null) {
            prefetchScope.launch {
                try {
                    val pages = fetchPageList(chapter).awaitSingle()
                    pageListCache[nextChKey] = pages
                    pages.forEachIndexed { index, page ->
                        val nextPage = pages.getOrNull(index + 1)
                        if (nextPage != null) {
                            pageToNextPage["${id}_${page.url}"] = nextPage
                        }
                    }
                } catch (e: Exception) {
                    // Ignore prefetch failures
                } finally {
                    inFlightPrefetches.remove(nextChKey)
                }
            }
        }
    }

    @Suppress("DEPRECATION")
    private fun triggerNextPagePrefetch(page: Page) {
        val pageKey = "${id}_${page.url}"
        val nextPage = pageToNextPage[pageKey] ?: return

        prefetchScope.launch {
            try {
                if (nextPage.imageUrl == null) {
                    val nextUrl = fetchImageUrl(nextPage).awaitSingle()
                    nextPage.imageUrl = nextUrl
                }
                // The image body is deliberately NOT downloaded here. The reader fetches images
                // through a cacheless client (newCachelessCallWithProgress), so these bytes were
                // never reused - every page could be downloaded 2-3 times concurrently, competing
                // with the visible page for bandwidth. HttpPageLoader's own priority preload
                // (which writes into ChapterCache) covers neighbour warming.
            } catch (e: Exception) {
                // Ignore prefetch failures
            }
        }
    }

    companion object {
        // Bounded, insertion-order-evicting caches: these live for the whole process and used to
        // grow without limit (chapter/page lists of every manga opened in a session) while also
        // keeping stale signed image URLs alive forever. Every consumer treats a miss as
        // "fetch from network", so eviction is safe.
        private val chapterListCache = BoundedCache<String, List<SChapter>>(maxSize = 25)
        private val pageListCache = BoundedCache<String, List<Page>>(maxSize = 100)
        private val chapterToMangaUrl = BoundedCache<String, String>(maxSize = 2000)
        private val mangaToChapters = BoundedCache<String, List<SChapter>>(maxSize = 25)
        private val pageToNextPage = BoundedCache<String, Page>(maxSize = 2000)
        private val inFlightPrefetches = ConcurrentHashMap<String, Boolean>()

        // Hard transport ceiling per image request: long enough for slow CDN strips on
        // mobile networks, short enough that a dead socket cannot pin a download worker
        // for a quarter of an hour.
        private const val IMAGE_CALL_TIMEOUT_MINUTES = 2L

        private val prefetchScope = CoroutineScope(
            Dispatchers.IO + SupervisorJob(),
        )
    }

    /**
     * Assigns the url of the chapter without the scheme and domain. It saves some redundancy from
     * database and the urls could still work after a domain change.
     *
     * @param url the full url to the chapter.
     */
    fun SChapter.setUrlWithoutDomain(url: String) {
        this.url = getUrlWithoutDomain(url)
    }

    /**
     * Assigns the url of the manga without the scheme and domain. It saves some redundancy from
     * database and the urls could still work after a domain change.
     *
     * @param url the full url to the manga.
     */
    fun SManga.setUrlWithoutDomain(url: String) {
        this.url = getUrlWithoutDomain(url)
    }

    /**
     * Returns the url of the given string without the scheme and domain.
     *
     * @param orig the full url.
     */
    private fun getUrlWithoutDomain(orig: String): String {
        return try {
            val uri = URI(orig.replace(" ", "%20"))
            var out = uri.path
            if (uri.query != null) {
                out += "?" + uri.query
            }
            if (uri.fragment != null) {
                out += "#" + uri.fragment
            }
            out
        } catch (e: URISyntaxException) {
            orig
        }
    }

    /**
     * Returns the url of the provided manga
     *
     * @since extensions-lib 1.4
     * @param manga the manga
     * @return url of the manga
     */
    open fun getMangaUrl(manga: SManga): String {
        return mangaDetailsRequest(manga).url.toString()
    }

    /**
     * Returns the url of the provided chapter
     *
     * @since extensions-lib 1.4
     * @param chapter the chapter
     * @return url of the chapter
     */
    open fun getChapterUrl(chapter: SChapter): String {
        return pageListRequest(chapter).url.toString()
    }

    /**
     * Called before inserting a new chapter into database. Use it if you need to override chapter
     * fields, like the title or the chapter number. Do not change anything to [manga].
     *
     * @param chapter the chapter to be added.
     * @param manga the manga of the chapter.
     */
    open fun prepareNewChapter(chapter: SChapter, manga: SManga) {}

    /**
     * Returns the list of filters for the source.
     */
    override fun getFilterList() = FilterList()
}

/**
 * Insertion-order bounded map used by the process-lifetime static caches in [HttpSource].
 * Evicts the eldest entry once [maxSize] is exceeded; all operations are lock-guarded because
 * prefetch coroutines and reader threads hit the caches concurrently.
 */
private class BoundedCache<K, V>(private val maxSize: Int) {

    private val map = object : LinkedHashMap<K, V>(16, 0.75f, false) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<K, V>?): Boolean = size > maxSize
    }

    private val lock = Any()

    operator fun get(key: K): V? = synchronized(lock) { map[key] }

    operator fun set(key: K, value: V) {
        synchronized(lock) { map[key] = value }
    }

    fun containsKey(key: K): Boolean = synchronized(lock) { map.containsKey(key) }
}
